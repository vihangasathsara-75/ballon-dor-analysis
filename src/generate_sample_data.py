"""Generate a clearly labelled SYNTHETIC player-performance sample.

This script does **not** scrape FBref or Transfermarkt and must not be
treated as a source of historical statistics. It exists so the analysis
pipeline can be developed while real official extracts are unavailable.

Identifiers (year, player, club, nationality, Wikipedia position when
present) are copied from ``data/raw/ballon_dor_voting.csv``. Every
performance statistic and trophy flag is simulated with a fixed seed
and written to ``data/sample/synthetic_player_season_stats.csv``.

Example:
    python src/generate_sample_data.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
VOTING_PATH = REPO_ROOT / "data" / "raw" / "ballon_dor_voting.csv"
OUTPUT_PATH = REPO_ROOT / "data" / "sample" / "synthetic_player_season_stats.csv"
SEED = 42
DATA_LABEL = "SYNTHETIC"


def performance_period(year: int) -> str:
    if year <= 2021:
        return f"{year} calendar year (SYNTHETIC period label)"
    return f"{year - 1}/{year} season (SYNTHETIC period label)"


def wikipedia_position_map(voting: pd.DataFrame) -> dict[str, str]:
    """Propagate a Wikipedia-listed position to earlier rows for the same player."""
    mapping: dict[str, str] = {}
    listed = voting.dropna(subset=["position"])
    for player, group in listed.groupby("player"):
        values = group["position"].dropna().unique().tolist()
        if values:
            mapping[player] = str(values[0])
    return mapping


def clip_int(values: np.ndarray, low: int, high: int) -> np.ndarray:
    return np.clip(np.rint(values), low, high).astype(int)


def generate(voting: pd.DataFrame, seed: int = SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    positions = wikipedia_position_map(voting)
    rows: list[dict] = []

    for record in voting.itertuples(index=False):
        wiki_position = record.position if isinstance(record.position, str) and record.position else None
        used_position = wiki_position or positions.get(record.player)
        position_source = (
            "wikipedia_same_year"
            if wiki_position
            else ("wikipedia_other_year" if used_position else "unspecified")
        )

        # Role only affects the synthetic distributions. It is not a real
        # official position when Wikipedia did not list one for that row.
        role = (used_position or "Midfielder").lower()
        if "goal" in role:
            goal_mean, assist_mean, minute_mean = 0.1, 0.2, 2800
        elif "defen" in role:
            goal_mean, assist_mean, minute_mean = 3.0, 2.5, 2600
        elif "mid" in role:
            goal_mean, assist_mean, minute_mean = 8.0, 8.0, 2500
        else:
            goal_mean, assist_mean, minute_mean = 18.0, 8.0, 2400

        # Weak, noisy association with award rank, for pipeline demonstration only.
        rank_boost = max(0.0, (15 - int(record.rank)) / 15)
        goals = clip_int(rng.normal(goal_mean + 10 * rank_boost, 5), 0, 55)
        assists = clip_int(rng.normal(assist_mean + 5 * rank_boost, 3.5), 0, 30)
        if "goal" in role:
            goals = np.array(0)
            assists = clip_int(rng.normal(0.2, 0.4), 0, 3)
        minutes = clip_int(rng.normal(minute_mean + 400 * rank_boost, 400), 400, 4500)
        appearances = clip_int(minutes / rng.uniform(70, 90) + rng.normal(0, 2), 8, 70)

        trophy_prob = 0.15 + 0.55 * rank_boost
        won_league = int(rng.random() < trophy_prob)
        won_ucl = int(rng.random() < trophy_prob * 0.45)
        won_domestic_cup = int(rng.random() < trophy_prob * 0.5)
        won_international = int(rng.random() < 0.08 + 0.2 * rank_boost)
        club_trophies = int(won_league + won_ucl + won_domestic_cup)

        rows.append(
            {
                "year": int(record.year),
                "player": record.player,
                "club": record.club,
                "nationality": record.nationality,
                "performance_period": performance_period(int(record.year)),
                "position": used_position,
                "position_source": position_source,
                "appearances": int(appearances),
                "minutes": int(minutes),
                "goals": int(goals),
                "assists": int(assists),
                "club_trophies": club_trophies,
                "won_domestic_league": won_league,
                "won_ucl": won_ucl,
                "won_domestic_cup": won_domestic_cup,
                "won_international_trophy": won_international,
                "data_label": DATA_LABEL,
                "source": (
                    "SYNTHETIC sample generated by src/generate_sample_data.py "
                    f"(seed={seed}). Not FBref or Transfermarkt data."
                ),
            }
        )

    return pd.DataFrame(rows)


def main() -> int:
    if not VOTING_PATH.exists():
        print(f"Missing {VOTING_PATH}. Collect voting data first.", file=sys.stderr)
        return 2
    voting = pd.read_csv(VOTING_PATH)
    sample = generate(voting)
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    sample.to_csv(OUTPUT_PATH, index=False)
    print(
        f"Wrote {len(sample)} SYNTHETIC rows to {OUTPUT_PATH.relative_to(REPO_ROOT)} "
        f"(seed={SEED})."
    )
    print(
        "Position coverage:",
        int((sample["position_source"] != "unspecified").sum()),
        "of",
        len(sample),
        "rows have a Wikipedia-derived position.",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
